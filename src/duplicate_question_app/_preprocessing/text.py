# Compile typo patterns once
_TYPO_PATTERNS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"\b" + re.escape(typo) + r"\b", re.IGNORECASE), correct) for typo, correct in _TYPO_MAP.items()
]


def fix_common_typos(text: str) -> str:
    """Fix common misspellings and typos in text."""
    result = text
    for pattern, correct in _TYPO_PATTERNS:
        result = pattern.sub(correct, result)
    return result


def normalize_question(text: str, expand_abbrevs: bool = True, fix_typos: bool = True) -> str:
    """Normalize a question text for inference.

    Steps:
    1. Strip whitespace
    2. Normalize unicode quotes and dashes to ASCII
    3. Strip HTML tags
    4. Replace URLs and emails with placeholders
    5. Remove emoji
    6. Normalize special characters and repeated punctuation
    7. Optionally expand abbreviations
    8. Fix common typos/misspellings
    9. Collapse multiple spaces
    10. Lowercase
    """
    text = str(text or "").strip()

    if not text:
        return ""

    # Normalize unicode quotes and dashes to ASCII equivalents
    text = text.replace("\u201c", '"').replace("\u201d", '"')
    text = text.replace("\u2018", "'").replace("\u2019", "'")
    text = text.replace("\u2013", "-").replace("\u2014", "--")

    # Strip HTML tags
    text = _strip_html(text)

    # Replace URLs and emails with placeholders
    text = _strip_urls(text)
    text = _strip_emails(text)

    # Remove emoji
    text = _strip_emoji(text)

    # Normalize special characters and repeated punctuation
    text = _normalize_special_chars(text)

    # Expand abbreviations (benefits semantic models greatly)
    if expand_abbrevs:
        text = expand_abbreviations(text)

    # Fix common typos
    if fix_typos:
        text = fix_common_typos(text)

    # Collapse multiple spaces (handles spaces inserted by expansion)
    text = re.sub(r"\s+", " ", text)

    # Lowercase
    text = text.lower()

    return text.strip()
