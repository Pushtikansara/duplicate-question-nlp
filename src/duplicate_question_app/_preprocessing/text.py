# Compile all patterns once
_ABBREV_PATTERNS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(pattern, re.IGNORECASE), expansion) for pattern, expansion in _ABBREVIATIONS.items()
]


def expand_abbreviations(text: str) -> str:
    """Expand common abbreviations in text by appending the full form.

    Appends the expanded form in parentheses after the first occurrence
    so that both the original token and the expanded form are available
    for downstream models. For example:
    'Explain AI.' → 'Explain AI. (Artificial Intelligence)'

    Skips expansion if the full form is already present in the text
    (handles cases like 'dbms (database management system)' correctly).
    """
    result = text
    seen: set[str] = set()
    for pattern, expansion in _ABBREV_PATTERNS:
        match = pattern.search(result)
        if match and expansion not in seen:
            match.group(0)
            # Skip if expansion is already present in text (e.g. parenthetical)
            if expansion.lower() in result.lower():
                seen.add(expansion)
                continue
            # Append expansion after the abbreviation
            result = result[: match.end()] + f" ({expansion})" + result[match.end() :]
            seen.add(expansion)
    return result


def _strip_html(text: str) -> str:
    """Remove HTML tags from text."""
    return re.sub(r"<[^>]+>", " ", text)


def _strip_urls(text: str) -> str:
    """Replace URLs with a placeholder token."""
    url_pattern = re.compile(
        r"https?://(?:www\.)?[-a-zA-Z0-9@:%._+~#=]{1,256}\.[a-zA-Z0-9()]{1,6}\b[-a-zA-Z0-9()@:%_+.~#?&/=]*"
        r"|www\.[-a-zA-Z0-9@:%._+~#=]{1,256}\.[a-zA-Z0-9()]{1,6}\b[-a-zA-Z0-9()@:%_+.~#?&/=]*"
        r"|[-a-zA-Z0-9@:%._+~#=]{2,256}\.[a-z]{2,6}\b[-a-zA-Z0-9@:%_+.~#?&/=]*",
        re.IGNORECASE,
    )
    return url_pattern.sub(" [url] ", text)


def _strip_emails(text: str) -> str:
    """Replace email addresses with a placeholder."""
    return re.sub(r"[\w.+-]+@[\w-]+\.[\w.-]+", " [email] ", text)


def _strip_emoji(text: str) -> str:
    """Remove emoji and other special Unicode symbols."""
    emoji_pattern = re.compile(
        "["
        "\U0001f600-\U0001f64f"  # emoticons
        "\U0001f300-\U0001f5ff"  # symbols & pictographs
        "\U0001f680-\U0001f6ff"  # transport & map symbols
        "\U0001f1e0-\U0001f1ff"  # flags
        "\U00002702-\U000027b0"  # dingbats
        "\U000024c2-\U0001f251"  # misc
        "]+",
        flags=re.UNICODE,
    )
    return emoji_pattern.sub(" ", text)


def _normalize_special_chars(text: str) -> str:
    """Normalize special characters and repeated punctuation."""
    # Replace repeated punctuation with single
    text = re.sub(r"([!?.])\1+", r"\1", text)
    # Normalize ellipsis
    text = re.sub(r"\.{3,}", "...", text)
    # Remove repeated commas/semicolons
    text = re.sub(r"[,;]{2,}", ",", text)
    return text


